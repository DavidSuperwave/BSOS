/**
 * GTM Daily Report
 *
 * Aggregates all metrics and sends daily report to Telegram
 *
 * Runs: 9:00 AM Daily
 */

require('dotenv').config();
const fetch = require('node-fetch');
const fs = require('fs');
const path = require('path');

// Load .env
const envPath = path.join(__dirname, '.env');
if (fs.existsSync(envPath)) {
  require('dotenv').config({ path: envPath });
}

// Configuration
const PLUSVIBE_API_KEY = process.env.PLUSVIBE_API_KEY;
const PLUSVIBE_WORKSPACE_ID = process.env.PLUSVIBE_WORKSPACE_ID || '678eb62a071ff7544034bcde';
const TELEGRAM_BOT_TOKEN = process.env.TELEGRAM_BOT_TOKEN;
const TELEGRAM_CHAT_ID = process.env.TELEGRAM_CHAT_ID || '1244663682';

// State files
const STATE_FILES = {
  leadAlerts: '.lead-alerts-state.json',
  volume: '.volume-tracker-state.json',
  deliverability: '.deliverability-state.json',
  campaignDetector: '.campaign-detector-state.json',
  replyMonitor: null // Would need to add
};

function loadState(file) {
  try {
    const filePath = path.join(__dirname, file);
    if (fs.existsSync(filePath)) {
      return JSON.parse(fs.readFileSync(filePath, 'utf8'));
    }
  } catch (e) { }
  return null;
}

// Get campaign metrics
async function getCampaignMetrics() {
  if (!PLUSVIBE_API_KEY) return null;
  
  try {
    const response = await fetch(
      `https://api.plusvibe.ai/api/v1/campaign/list?workspace_id=${PLUSVIBE_WORKSPACE_ID}`,
      {
        headers: { 'x-api-key': PLUSVIBE_API_KEY }
      }
    );
    
    const data = await response.json();
    const campaigns = data.data || [];
    
    const active = campaigns.filter(c => c.status === 'ACTIVE').length;
    const draft = campaigns.filter(c => c.status === 'DRAFT').length;
    const completed = campaigns.filter(c => c.status === 'COMPLETED').length;
    
    return { total: campaigns.length, active, draft, completed };
  } catch (error) {
    return null;
  }
}

// Get lead counts
async function getLeadCounts() {
  if (!PLUSVIBE_API_KEY) return null;
  
  try {
    const response = await fetch(
      `https://api.plusvibe.ai/api/v1/lead/counts?workspace_id=${PLUSVIBE_WORKSPACE_ID}`,
      {
        headers: { 'x-api-key': PLUSVIBE_API_KEY }
      }
    );
    
    return await response.json();
  } catch (error) {
    return null;
  }
}

// Generate report
