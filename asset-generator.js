// Send to Telegram
async function sendAsset(asset, type) {
  if (!TELEGRAM_BOT_TOKEN) {
    console.log('\n' + asset);
    return;
  }
  
  try {
    await fetch(`https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        chat_id: TELEGRAM_CHAT_ID,
        text: asset,
        parse_mode: 'HTML'
      })
    });
    console.log('   ✅ Sent to Telegram');
  } catch (error) {
    console.error('Telegram error:', error.message);
  }
}

// Main
async function main() {
  const args = process.argv.slice(2);
  const email = args.find(a => a.startsWith('--email='))?.split('=')[1];
  const type = args.find(a => a.startsWith('--type='))?.split('=')[1] || 'brief';
  
  if (!email) {
    console.log('Usage: node asset-generator.js --email=john@company.com --type=brief|nurture|faq');
    return;
  }
  
  console.log(`[Asset Generator] Generating ${type} for ${email}...`);
  
  const reply = {
    from_email: email,
    from_name: email.split('@')[0],
    campaign_name: 'Superwave Campaign',
    subject: 'Following up'
  };
  
  const icp = await getICP(email.split('@')[1]);
  
  let asset;
  switch (type) {
    case 'nurture':
      asset = generateNurture(reply, icp);
      break;
    case 'faq':
      asset = generateFAQ(reply, icp);
      break;
    default:
      asset = generateBrief(reply, icp);
  }
  
  await sendAsset(asset, type);
}

module.exports = { generateBrief, generateNurture, generateFAQ };

if (require.main === module) {
  main().catch(console.error);
}
